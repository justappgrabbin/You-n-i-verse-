import assert from 'node:assert/strict';
import {createSimulation} from './simState.mjs';
import {createAdventureBridge} from './adventureBridge.mjs';
const charts=[1,2,3,4].map(n=>({id:'c'+n,system:'unresolved-source',address:'gate:'+n}));
const rules=[{id:'fixture-allow',source:'test-fixture-not-hd',chartId:'c1',address:'gate:1',actionId:'step',effect:'allow'},{id:'fixture-deny',source:'test-fixture-not-hd',chartId:'c2',address:'gate:2',actionId:'step',effect:'deny',when:{locked:true}}];
const initialState=createSimulation({agents:[{id:'sim',charts,position:{x:0,y:0}}],world:{visited:false},successConditions:[{id:'arrival',scope:'world',key:'visited',equals:true}]});
const scenes=[{id:'entry',choices:[{id:'enter',action:{id:'step',effects:{position:{x:2,y:3},world:{visited:true}}},nextScene:'garden'}]},{id:'garden',choices:[]}];
const events=[];const game=createAdventureBridge({initialState,rules,scenes,onEvent:e=>events.push(e)});
assert.equal(game.snapshot().currentScene,'entry');
const blocked=game.choose({agentId:'sim',choiceId:'enter',context:{locked:true}});
assert.equal(blocked.applied,false);assert.equal(game.snapshot().state.tick,0);assert.equal(events.length,0);
const unresolved=createAdventureBridge({initialState,rules:rules.map(r=>({...r,actionId:'different'})),scenes});
assert.equal(unresolved.choose({agentId:'sim',choiceId:'enter'}).decision.status,'unresolved');
const accepted=game.choose({agentId:'sim',choiceId:'enter',context:{locked:false}});
assert.equal(accepted.applied,true);assert.equal(accepted.event.position.x,2);assert.equal(accepted.event.success[0].met,true);
assert.equal(game.snapshot().currentScene,'garden');assert.equal(events.length,1);
const restored=createAdventureBridge({initialState,rules,scenes});restored.load(game.save());assert.deepEqual(restored.snapshot(),game.snapshot());
assert.equal(initialState.world.visited,false);
assert.throws(()=>game.choose({agentId:'sim',choiceId:'missing'}),/Unknown choice/);
assert.throws(()=>createAdventureBridge({initialState,rules,scenes:[...scenes,scenes[0]]}),/unique id/);
console.log('10 adventure bridge assertions passed');
