import assert from 'node:assert/strict';
import {createSimulation,perceive,transition,evaluateSuccess,serializeSimulation,restoreSimulation} from './simState.mjs';
const charts=[1,2,3,4].map(n=>({id:'c'+n,system:'source-pending',address:'gate:'+n}));
const rules=[{id:'r1',source:'test fixture only',chartId:'c1',address:'gate:1',actionId:'collect',effect:'allow'},{id:'r2',source:'test fixture only',chartId:'c2',address:'gate:2',actionId:'collect',effect:'deny',when:{locked:true}}];
const initial=createSimulation({agents:[{id:'sim-1',charts,goals:['collect'],position:{x:0,y:0}}],world:{collected:false},successConditions:[{id:'goal',scope:'world',key:'collected',equals:true}]});
assert.equal(perceive(initial,'sim-1').position.x,0);
assert.equal(evaluateSuccess(initial)[0].met,false);
const action={id:'collect',effects:{world:{collected:true},position:{x:1,y:0},agentState:{energy:2}}};
const blocked=transition(initial,{agentId:'sim-1',action,rules,context:{locked:true}});
assert.equal(blocked.decision.status,'denied');assert.equal(blocked.applied,false);assert.equal(blocked.state.tick,0);
const unresolved=transition(initial,{agentId:'sim-1',action:{id:'unknown'},rules});
assert.equal(unresolved.decision.status,'unresolved');assert.equal(unresolved.applied,false);
const moved=transition(initial,{agentId:'sim-1',action,rules,context:{locked:false}});
assert.equal(moved.applied,true);assert.equal(moved.state.tick,1);assert.equal(moved.state.agents[0].memory.length,1);
assert.equal(moved.state.agents[0].position.x,1);assert.equal(evaluateSuccess(moved.state)[0].met,true);
assert.deepEqual(restoreSimulation(serializeSimulation(moved.state)),moved.state);
assert.equal(initial.world.collected,false);
assert.throws(()=>createSimulation({agents:[{id:'a',charts:[]}]}),/four charts/);
console.log('11 simulation behavior assertions passed');
